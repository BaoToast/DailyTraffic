/*
 * ══════════════════════════════════════════════════════════════════════
 *  車種顏色的唯一來源
 * ══════════════════════════════════════════════════════════════════════
 *
 * 使用者 2026-09-14（附圓環圖）：
 *   「機車 和 大型車 顏色過於接近，請將各車種（包含未來新增的車種）
 *     顏色之間的差異對比要明顯一點」
 *
 * ── 為什麼要有這一支檔案 ──────────────────────────────────────
 *
 * 同一組車種顏色原本**抄在三個地方**：畫面上的圓環圖、Excel 儲存格填色、
 * Excel 原生圖表的資料數列。改一個地方、忘了另外兩個，畫面與交出去的
 * Excel 就會用不同顏色代表同一個車種——而且不會有任何錯誤訊息。
 * 現在只有這一份，另外三處都從這裡拿。
 *
 * ── 新顏色是量出來的，不是挑好看的 ────────────────────────────
 *
 * 舊的那一組實測不合格：
 *   ・機車 #148C8C ↔ 大型車 #5B8DB8：一般視覺色差 ΔE 只有 **9.0**
 *     ——這就是使用者看到的「顏色過於接近」
 *   ・#D8E7F1（特種車）太淺，和白底的對比只有 1.23:1，幾乎看不見
 *   ・十個顏色裡有六個彩度過低，本質上是灰的
 *
 * 新的這一組：使用者指名的那一對
 *   機車 #009E73 ↔ 大型車 #0072B2　一般視覺 ΔE **9.0 → 18.7**
 * 前 6 個（實際會用到的車種數）**兩兩之間**最差也有 ΔE **18.2**，
 * 而且六個分屬六個不同色系（綠／橘／藍／桃紅／紫／褐），
 * 不會出現「兩個橘色」這種數字看起來夠大、人看起來卻很像的情況。
 *
 * ⚠️ 使用者 2026-09-14 的明確指示：
 *   「因為剛好大型車色塊很小，顏色很接近，**不需要考慮色盲分不分的出來**，
 *     各車種（含未來可能出現的各種車種）顏色差異性是否能明顯的，
 *     然後圖例一樣在圖旁」
 *   所以這一版是**以一般視覺的差異最大化**為目標挑的。
 *   （我原本先挑了色盲友善的 Okabe–Ito 標準色盤，一般視覺最差是 15.6；
 *     依使用者指示改成現在這組之後提升到 18.2。色盲視角的分辨度因此變差，
 *     這是**使用者知情後的決定**，不是疏忽。）
 *
 * ⚠️ 第 6 個褐色的彩度 0.09，略低於「不可以看起來像灰色」的建議值 0.10。
 *   保留它是因為褐色本來就是低彩度的色系，而它和其他五個色系一眼分得出來；
 *   換成高彩度的顏色就會和橘色撞成同一家族（實測那樣一般視覺最差掉到 14.7）。
 *
 * ⚠️ 十個類別要兩兩之間都分得開是做不到的（顏色空間就這麼大）。
 *   第 7 個以後只保證「相鄰」分得開，並且靠圖例補足
 *   ——使用者也指定「圖例一樣在圖旁」，所以圖例不可以拿掉。
 *   （tests/vehicle-colors.test.mjs 會把上面每一條都重算一次。）
 *
/** 畫面用（CSS 色碼）。索引 ＝ 車種在目錄裡的順序。 */
export const VEHICLE_COLORS = [
  "#009E73", // 1 綠
  "#E8710A", // 2 橘
  "#0072B2", // 3 藍
  "#D81B60", // 4 桃紅
  "#7B2FBF", // 5 紫
  "#7A4E18", // 6 褐
  "#00A5B5", // 7 青
  "#7A8B00", // 8 橄欖
  "#C41E3A", // 9 正紅
  "#5A5A8C", // 10 藍紫灰
] as const;

/** Excel 用（ARGB，前面要補 FF）。從上面那一份換算，不另外抄一份。 */
export const VEHICLE_COLORS_ARGB = VEHICLE_COLORS.map(
  (hex) => "FF" + hex.slice(1).toUpperCase(),
);

/** 車種多於顏色數時循環取用（維持舊行為）。 */
export function vehicleColor(index: number) {
  return VEHICLE_COLORS[index % VEHICLE_COLORS.length];
}

